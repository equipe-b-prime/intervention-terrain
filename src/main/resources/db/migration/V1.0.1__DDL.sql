-- Type d'intervention
CREATE TABLE IF NOT EXISTS types_intervention (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    delai_heures INTEGER NOT NULL
);

-- Compétences requises par type d'intervention (table d'association métier F13 / F17)
CREATE TABLE IF NOT EXISTS type_intervention_competence (
    type_intervention_id BIGINT NOT NULL,
    competence_id BIGINT NOT NULL,
    PRIMARY KEY (type_intervention_id, competence_id),
    CONSTRAINT fk_typecomp_type FOREIGN KEY (type_intervention_id) REFERENCES types_intervention(id),
    CONSTRAINT fk_typecomp_competence FOREIGN KEY (competence_id) REFERENCES competence(id)
);

-- Créneau horaire
CREATE TABLE IF NOT EXISTS creneau (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_debut TIME WITHOUT TIME ZONE NOT NULL,
    date_fin TIME WITHOUT TIME ZONE NOT NULL
);

-- Client
CREATE TABLE IF NOT EXISTS client (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(180),
    telephone VARCHAR(30),
    adresse VARCHAR(255),
    commune VARCHAR(120)
);

-- Statut de référence (PLANIFIEE, EN_COURS, TERMINEE, ECHOUEE, ANNULEE, etc.)
CREATE TABLE IF NOT EXISTS statut (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(255) NOT NULL
);

-- Intervention
CREATE TABLE IF NOT EXISTS intervention (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_planifiee DATE NOT NULL,
