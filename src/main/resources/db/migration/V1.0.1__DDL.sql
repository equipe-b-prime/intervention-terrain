-- =========================================================================
-- 0. NETTOYAGE PRÉALABLE DES VUES (ou tables Hibernate créées par mégarde)
-- =========================================================================
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN (
        SELECT tablename, 'TABLE' AS type FROM pg_tables WHERE schemaname = 'public' 
            AND tablename IN ('v_technicien_disponible', 'v_taux_reussite_agence', 'v_intervention_stats')
        UNION ALL
        SELECT viewname AS tablename, 'VIEW' AS type FROM pg_views WHERE schemaname = 'public' 
            AND viewname IN ('v_technicien_disponible', 'v_taux_reussite_agence', 'v_intervention_stats')
    ) LOOP
        EXECUTE 'DROP ' || r.type || ' IF EXISTS public.' || quote_ident(r.tablename) || ' CASCADE';
    END LOOP;
END $$;

