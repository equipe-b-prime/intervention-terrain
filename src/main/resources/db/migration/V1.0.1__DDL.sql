-- Région
CREATE TABLE IF NOT EXISTS region (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL
);

-- Département
CREATE TABLE IF NOT EXISTS departement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    code VARCHAR(10) NOT NULL,
    region_id BIGINT NOT NULL,
    CONSTRAINT fk_departement_region FOREIGN KEY (region_id) REFERENCES region(id)
);

-- Commune
CREATE TABLE IF NOT EXISTS commune (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(120) NOT NULL,
    code_postal VARCHAR(10) NOT NULL,
    departement_id BIGINT NOT NULL,
    CONSTRAINT fk_commune_departement FOREIGN KEY (departement_id) REFERENCES departement(id)
);

-- Agence
CREATE TABLE IF NOT EXISTS agence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(120) NOT NULL,
    ville VARCHAR(100),
    responsable VARCHAR(120),
    commune_id BIGINT NOT NULL,
    CONSTRAINT fk_agence_commune FOREIGN KEY (commune_id) REFERENCES commune(id)
);

-- Équipe
CREATE TABLE IF NOT EXISTS equipe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(120) NOT NULL,
    agence_id BIGINT NOT NULL,
    CONSTRAINT fk_equipe_agence FOREIGN KEY (agence_id) REFERENCES agence(id)
);

-- Technicien
CREATE TABLE IF NOT EXISTS technicien (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(180),
    telephone VARCHAR(30),
    matricule VARCHAR(50),
    equipe_id BIGINT NOT NULL,
    CONSTRAINT fk_technicien_equipe FOREIGN KEY (equipe_id) REFERENCES equipe(id)
);

-- Compétence
CREATE TABLE IF NOT EXISTS competence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    date_obtention DATE,
    date_expiration DATE
);

-- Association Technicien - Compétence
CREATE TABLE IF NOT EXISTS technicien_competence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technicien_id BIGINT NOT NULL,
    competence_id BIGINT NOT NULL,
    date_obtention DATE NOT NULL,
    date_expiration DATE,
    CONSTRAINT fk_techcomp_technicien FOREIGN KEY (technicien_id) REFERENCES technicien(id),
    CONSTRAINT fk_techcomp_competence FOREIGN KEY (competence_id) REFERENCES competence(id)
