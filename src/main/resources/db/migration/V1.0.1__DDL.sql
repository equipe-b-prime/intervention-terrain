-- Pièce détachée / matériel
CREATE TABLE IF NOT EXISTS piece (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(120) NOT NULL,
    reference VARCHAR(120) NOT NULL,
    description VARCHAR(500)
